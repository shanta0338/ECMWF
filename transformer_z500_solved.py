def train_one_epoch(model, loader, optimiser, criterion, latlon):
    model.train()
    total_loss = 0.0
    for x, y in loader:
        optimiser.zero_grad()
        pred = model(x, latlon)
        loss = criterion(pred, y)
        loss.backward()
        optimiser.step()
        total_loss += loss.item() * x.size(0)
    return total_loss / len(loader.dataset)


def evaluate(model, loader, criterion, latlon):
    model.eval()
    total_loss = 0.0
    with torch.no_grad():
        for x, y in loader:
            pred = model(x, latlon)
            loss = criterion(pred, y)
            total_loss += loss.item() * x.size(0)
    return total_loss / len(loader.dataset)

